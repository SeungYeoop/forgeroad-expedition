const EN = 600;
function shaft(K, x, fu, fd, k = "ladder", m = null) {
  K.air(x - 1, fu, x + 2, fd);
  m && K.wall(x - 1, fu, x + 2, fd, m);
  K.plank(x - 1, x + 2, fu);
  k === "ladder" ? K.ladder(x, fu, fd) : k === "rope" ? K.rope(x, fu - 3, fd) : K.vine(x - 1, x + 2, fu - 3, fd);
}
const P = (K, x, f, k, o) => K.prop(x, f, k, o);
// 매달린 종유석 (천장 y0에서 길이 L, 밑동 폭 w → 끝이 뾰족)
function stalactite(K, cx, y0, L, w) {
  for (let k = 0; k < L; k++) {
    const hw = Math.max(0, Math.round(w * (1 - k / L) ** 0.8));
    K.rock(cx - hw, y0 + k, cx + hw + 1, y0 + k + 1);
  }
}

