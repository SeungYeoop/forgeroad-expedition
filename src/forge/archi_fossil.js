// 잿빛 그림자 심연 (g1_2, 노랑) 「거대 짐승 화석 무덤」 — 드립스톤 밑 바위 속에 통째로 묻힌 옛 짐승의 뼈
//   지도 = 칸 1024 × 1056 · 입구·출구 줄 600 · ▲ = 발굴 야영지 꼭대기 도르래 (x 150) · ▼ = 타르 늪 가운데 뼈 섬
//   짐승은 서쪽 꼬리에서 동쪽 머리까지 지도를 가로질러 누워 있다
//     등뼈 굴(줄 300): 마디뼈가 천장·바닥에 솟은 긴 굴, 마디 사이 좁은 틈
//     갈비뼈 공동(가운데): 등뼈에서 아래로 휘어 내린 갈비뼈 여섯 — 뼈 사이 걸침 판 세 층 · 배 속 위석(보물)
//     머리뼈 동굴(동): 눈구멍 방 둘 · 콧구멍 굴 · 이빨이 늘어진 턱 홀
//     꼬리 나선(서): 꼬리뼈를 따라 감아 내려가는 굴
//     발굴 야영지(서쪽 위): 나무 비계 · 천막 · 도르래 승강기 (▲)
//     줄 600 대로: 갈비뼈 밑 배 굴 · 턱 밑 길
//     맨 아래: 타르 늪 (검은 물 · 떠다니는 뼈 판 · 가운데 뼈 섬 ▼)
//   장치: 승강기 · 사다리·밧줄 · 짚라인 · 무너지는 판 · 떨어지는 바위 · 금 간 벽 · 간헐천(타르 거품) · 회복 샘
// ══════════════════════════════════════════════════════════════

const EN = 600;
const P = (K, x, f, k, o) => K.prop(x, f, k, o);
function shaft(K, x, fu, fd, k = "ladder", m = null) {
  K.air(x - 1, fu, x + 2, fd);
  m && K.wall(x - 1, fu, x + 2, fd, m);
  K.plank(x - 1, x + 2, fu);
  k === "ladder" ? K.ladder(x, fu, fd) : k === "rope" ? K.rope(x, fu - 3, fd) : K.vine(x - 1, x + 2, fu - 3, fd);
}
// 뼈 (밝은 돌 재질로 칠한 바위)
const bone = (K, x0, y0, x1, y1) => (K.rock(x0, y0, x1, y1), K.mat(x0, y0, x1, y1, "brick"));

export function fossil(K) {
  camp(K);
  spine(K);
  ribcage(K);
  skull(K);
  tail(K);
  road(K);
  tarPits(K);
}

// ═══ 발굴 야영지 (서쪽 위): 비계 · 천막 · 도르래 승강기 (▲) ═══
function camp(K) {
  K.air(60, 90, 250, 200);
  for (let x = 60; x < 250; x++) {
    const v = Math.round(Math.sin(x * 0.07) * 4 + Math.sin(x * 0.19) * 2);
    v > 0 ? K.air(x, 90 - v, x + 1, 90) : K.rock(x, 90, x + 1, 90 - v);
  }
  K.rock(56, 200, 254, 206);
  // 비계 (판자 층 셋, 높이·폭 제각각)
  for (const [a, b, f] of [[80, 140, 170], [150, 220, 140], [90, 160, 116]]) K.plank(a, b, f);
  K.wall(80, 116, 82, 200, "stem"), K.wall(138, 116, 140, 200, "stem"), K.wall(218, 140, 220, 200, "stem");
  K.ladder(84, 170, 200), K.ladder(214, 140, 200), K.ladder(152, 116, 140), K.ladder(96, 116, 170);
  // 도르래 꼭대기 (▲)
  K.rock(130, 100, 172, 104), K.ladder(150, 100, 116);
  K.peak(150, 100);
  P(K, 140, 100, "p_wheel"), P(K, 164, 100, "p_lamp");
  K.tag(132, 86, 170, 100, "rest", { safe: 1 });
  for (const [x, f, k] of [[100, 200, "p_yurt"], [190, 200, "p_crates"], [230, 200, "p_rack"], [120, 170, "p_lantern"], [180, 140, "p_crates"], [110, 116, "p_shelf"]]) P(K, x, f, k === "p_lantern" ? "p_lamp" : k);
  K.heal(240, 248, 196, 200);
  K.tag(60, 180, 250, 200, "rest"), K.tag(150, 126, 220, 140, "treasure");
  K.struct("발굴 야영지", "▲ 드립스톤으로 · 쉼터", 56, 84, 254, 206);
  // 야영지 → 등뼈 굴 (비탈)
  K.ramp(250, 200, 300, 250, 9), K.ramp(300, 250, 350, 300, 9);
}

// ═══ 등뼈 굴 (줄 300): 마디뼈가 솟은 긴 굴 ═══
function spine(K) {
  K.hall(350, 860, 300, 14);
  for (let x = 400, i = 0; x < 850; x += 26 + ((i * 7) % 9), i++) {
    bone(K, x, 286, x + 8, 288 + (i % 2)); // 천장 마디
    bone(K, x + 14, 298, x + 19, 300); // 바닥 마디 (천장 마디와 엇갈려, 넘는다)
  }
  P(K, 420, 297, "p_bones", { s: 1 }), P(K, 600, 297, "p_skulls"), P(K, 760, 297, "p_bones");
  K.tag(360, 286, 840, 300, "arena");
  K.struct("등뼈 굴", "전투", 330, 284, 860, 302);
}

// ═══ 갈비뼈 공동: 등뼈에서 아래로 휜 갈비뼈, 사이에 걸침 판 셋 ═══
function ribcage(K) {
  K.sell(560, 450, 220, 138, 2.6, -1, 0.04);
  K.air(380, 302, 740, 312);
  // 갈비뼈: 등뼈 밑에서 바깥으로 휘었다가 아래로 (윗부분만 단단한 뼈, 아래는 뒷벽 뼈)
  for (const [x, dir, L] of [[400, -1, 220], [470, -1, 250], [540, -1, 260], [600, 1, 260], [670, 1, 240], [730, 1, 200]]) {
    for (let k = 0; k < L; k++) {
      const t = k / L, xx = Math.round(x + dir * Math.sin(t * 1.6) * 46), y = 316 + k;
      t < 0.12 ? bone(K, xx - 2, y, xx + 3, y + 1) : K.wall(xx - 2, y, xx + 3, y + 1, "brick");
    }
  }
  // 걸침 판 (뼈 사이, 높이 제각각)
  for (const [a, b, f] of [[380, 470, 400], [500, 610, 380], [640, 740, 410], [420, 540, 480], [580, 700, 470], [470, 650, 540]]) K.plank(a, b, f);
  for (const [x, a, b] of [[386, 400, 588], [506, 380, 480], [736, 410, 588], [424, 480, 588], [690, 470, 588], [476, 540, 588], [640, 410, 470]]) K.ladder(x, a, b);
  // 등뼈 굴 바닥에서 공동으로 (사다리 구멍)
  shaft(K, 560, 300, 380, "rope");
  // 배 속 위석 (보물): 걸침 판 가운데 위
  P(K, 560, 380, "p_ore", { s: 2 }), P(K, 520, 400, "p_bones", { s: 2 }), P(K, 660, 410, "p_bones", { s: 1 }), P(K, 600, 470, "p_skulls");
  K.tag(500, 366, 610, 380, "treasure"), K.tag(420, 466, 540, 480, "arena"), K.tag(580, 456, 700, 470, "arena"), K.tag(470, 526, 650, 540, "rest");
  K.fall(450, 456, 330, 480), K.fall(700, 706, 330, 470);
  K.struct("갈비뼈 공동", "보물·전투", 340, 312, 780, 590);
}

// ═══ 머리뼈 동굴 (동): 눈구멍 방 · 콧구멍 굴 · 턱 홀 ═══
function skull(K) {
  // 머리뼈 겉 (큰 뼈 덩어리) — 등뼈 굴 동쪽 끝에 이어진다
  // 머리뼈 실루엣: 둥근 머리통 + 앞으로 내민 주둥이 + 아래턱
  for (let y = 232; y < 534; y++) {
    const cr = y < 430 ? Math.sqrt(Math.max(0, 1 - ((y - 330) / 100) ** 2)) * 76 : 0;
    const jaw = y >= 380 ? (y < 450 ? 74 : 74 - (y - 450) * 0.5) : 0;
    const a = y < 430 ? 936 - cr : 862 + Math.max(0, (y - 450) * 0.6), b = y < 430 ? 936 + cr : 862 + jaw * 2;
    b > a && K.mat(Math.round(a), y, Math.round(Math.max(b, y >= 380 ? 1010 : b)), y + 1, "brick");
  }
  // 뇌 방 (위): 둥근 방
  K.ell(930, 300, 50, 24), K.air(884, 296, 976, 320), K.rock(880, 320, 980, 324);
  K.air(856, 290, 864, 300), K.ramp(862, 300, 886, 320, 10);
  P(K, 930, 320, "p_altar"), P(K, 906, 320, "p_candles"), P(K, 954, 320, "p_candles", { s: 1 });
  K.tag(888, 280, 972, 320, "rest");
  // 눈구멍 방 둘 (둥근, 높이가 다르다) + 사다리
  K.ell(900, 372, 22, 16), K.rock(876, 384, 924, 390), K.ell(962, 380, 18, 14), K.rock(942, 390, 982, 396);
  shaft(K, 900, 320, 384), shaft(K, 966, 320, 390);
  P(K, 900, 384, "p_crystal", { s: 2 }), P(K, 962, 390, "p_crystal", { s: 1 });
  K.tag(880, 360, 920, 384, "treasure"), K.tag(946, 370, 978, 390, "treasure");
  // 콧구멍 굴 → 턱 홀
  shaft(K, 920, 384, 520);
  // 턱 홀: 위에서 이빨이 늘어진 넓은 방 (대로 줄 600 위)
  K.air(860, 450, 1010, 520), K.rock(856, 520, 1014, 526);
  for (let x = 866; x < 1004; x += 12) {
    const L = 8 + ((x * 13) % 10);
    for (let k = 0; k < L; k++) bone(K, x - Math.max(0, 2 - (k >> 2)), 450 + k, x + 2 + Math.max(0, 2 - (k >> 2)) - 1, 451 + k);
  }
  K.plank(880, 930, 490), K.ladder(884, 490, 520);
  P(K, 900, 490, "p_bones", { s: 2 }), P(K, 960, 520, "p_skulls"), P(K, 990, 520, "p_bones");
  K.tag(862, 500, 1008, 520, "arena");
  shaft(K, 990, 520, EN, "ladder");
  K.struct("머리뼈 동굴", "보물·쉼터·전투", 856, 230, 1014, 526);
}

// ═══ 꼬리 나선 (서): 꼬리뼈를 따라 감아 내려간다 ═══
function tail(K) {
  K.wiggle([[384, 300], [324, 360], [254, 410], [194, 450], [140, 470]], 9, 1);
  K.hall(60, 142, 470, 12);
  K.wiggle([[60, 470], [100, 510], [150, 540]], 9, 1);
  K.hall(150, 260, 540, 14);
  for (let x = 160; x < 250; x += 18) bone(K, x, 536, x + 6, 540);
  P(K, 200, 536, "p_bones", { s: 1 }), P(K, 90, 470, "p_nest");
  K.tag(150, 526, 260, 540, "arena"), K.tag(62, 458, 118, 470, "treasure");
  K.ramp(260, 540, 320, EN, 9);
  K.fall(220, 226, 300, 380);
  K.struct("꼬리 나선", "전투·보물", 56, 296, 330, EN);
}

// ═══ 줄 600 대로: 배 굴 · 턱 밑 길 ═══
function road(K) {
  K.hall(0, 1024, EN, 12);
  // 갈비뼈 공동 밑을 지날 땐 천장이 뼈 아치
  for (const x of [396, 426, 516, 546, 576, 606, 636, 700]) bone(K, x, EN - 13, x + 10, EN - 11);
  K.tag(2, EN - 12, 50, EN, "rest", { safe: 1 }), K.tag(970, EN - 12, 1022, EN, "rest", { safe: 1 });
  K.tag(320, EN - 12, 520, EN, "arena"), K.tag(600, EN - 12, 840, EN, "arena");
  P(K, 100, EN, "p_lamp"), P(K, 300, EN, "p_crates"), P(K, 860, EN, "p_bones", { s: 1 });
  // 금 간 벽 뒤 도굴꾼 은신처
  K.crack(840, EN + 1, 844, EN + 12);
  K.air(844, EN, 900, EN + 12), K.rock(840, EN + 12, 900, EN + 16), K.ladder(870, EN - 2, EN + 12);
  P(K, 880, EN + 12, "p_crates", { s: 1 }), K.tag(844, EN, 900, EN + 12, "treasure");
  K.struct("화석 대로", "입구·출구", 0, EN - 14, 1024, EN + 16);
}

// ═══ 타르 늪 (맨 아래): 검은 물 · 떠다니는 뼈 판 · 가운데 뼈 섬 ▼ ═══
function tarPits(K) {
  K.sell(512, 880, 440, 110, 3, -1, 0.05);
  K.rock(60, 960, 964, 990);
  K.water(80, 930, 944, 960);
  // 뼈 판 (떠 있는 듯한 큰 뼈 조각): 높이·폭 제각각
  for (const [a, b, f] of [[100, 150, 928], [190, 230, 924], [270, 330, 930], [370, 410, 926], [610, 650, 925], [690, 750, 929], [790, 830, 924], [870, 930, 928]]) bone(K, a, f, b, f + 4);
  bone(K, 460, 916, 566, 960);
  K.deep(512, 916);
  P(K, 490, 916, "p_skulls"), P(K, 530, 916, "p_bones", { s: 2 }), P(K, 512, 916, "p_altar");
  K.tag(480, 902, 548, 916, "rest", { safe: 1 });
  K.geyser(440, 446, 880, 960), K.geyser(580, 586, 870, 960);
  for (const [a, b, f] of [[120, 930], [300, 930], [720, 929], [900, 928]]) K.tag(a - 14, b - 14, a + 14, b, "arena");
  // 위와 잇기
  shaft(K, 120, EN, 928), shaft(K, 900, EN, 928), shaft(K, 512, 540, 916, "rope");
  K.struct("타르 늪", "▼ 아래로·헤엄", 60, 770, 964, 990);
}
