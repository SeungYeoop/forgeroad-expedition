const EN = 600;
const P = (K, x, f, k, o) => K.prop(x, f, k, o);
function shaft(K, x, fu, fd, k = "ladder", m = null) {
  K.air(x - 1, fu, x + 2, fd);
  m && K.wall(x - 1, fu, x + 2, fd, m);
  K.plank(x - 1, x + 2, fu);
  k === "ladder" ? K.ladder(x, fu, fd) : k === "rope" ? K.rope(x, fu - 3, fd) : K.vine(x - 1, x + 2, fu - 3, fd);
}
// 방울: 둥근 공동, 바닥은 f에서 평평 (그 아래 채움)
function bulb(K, cx, cy, rx, ry, f) {
  K.ell(cx, cy, rx, ry, -1, 0.06);
  // 아래쪽은 넓고 평평하게 (모래가 쌓인 바닥)
  for (let y = Math.round(cy); y < f; y++) {
    const t = (y - cy) / Math.max(1, f - cy), w = Math.round(rx * (0.98 - t * 0.1));
    K.air(cx - w, y, cx + w, y + 1);
  }
  K.rock(cx - rx - 3, f, cx + rx + 3, cy + ry + 4);
}
// 모래 언덕 바닥: a~b 사이 완만한 둔덕 (윗면 f에서 최대 h 높이)
function dunes(K, a, b, f, h, s) {
  for (let x = a; x < b; x++) {
    const v = Math.max(0, Math.round((Math.sin((x - a) * 0.05 + s) * 0.5 + 0.5) * h * Math.sin(((x - a) / (b - a)) * Math.PI)));
    v > 0 && (K.rock(x, f - v, x + 1, f), K.mat(x, f - v, x + 1, f, "brick"));
  }
}

export function hourglass(K) {
  west(K);
  center(K);
  east(K);
  road(K);
  under(K);
}

