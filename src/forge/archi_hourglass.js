//   지도 = 칸 1024 × 1056 · 입구·출구 줄 600 · ▲ = 가운데 모래시계 위 방울 꼭대기 · ▼ = 모래 강 가운데 섬
//   공동마다 모래시계 꼴(위 방울 · 좁은 목 · 아래 방울), 크기와 쓰임이 다르다
//     서쪽 모래시계: 위 = 유리 공방(가마 셋 · 걸침 판), 목 = 밧줄, 아래 = 모래 언덕 계단
//     가운데 모래시계: 위 = 별 유리 천문대(▲), 목 = 사다리 굴, 아래 = 모래 폭포 홀(위로 부는 바람)
//     동쪽 모래시계: 위 = 유리 정원(결정 숲), 목 = 덩굴, 아래 = 무너진 상단 야영지
//     밑: 거꾸로 선 모래시계(넓은 위 · 좁은 아래) · 모래 강 (징검 유리판 · 가운데 섬 ▼)
//   장치: 밧줄·사다리·덩굴 · 바람(모래 폭포) · 짚라인 · 무너지는 판 · 금 간 벽 · 간헐천(모래 분출) · 회복 샘
