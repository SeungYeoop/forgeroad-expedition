  K.air(380, 960, 644, 1000);
  for (const [a, b, f] of [[392, 440, 980], [584, 632, 976]]) (K.rock(a, f, b, 1000), K.mat(a, f, b, f + 3, "brick"));
  K.ladder(388, 980, 1000), K.ladder(636, 976, 1000), K.ladder(443, 980, 1000), K.ladder(581, 976, 1000);
  K.deep(512, 1000);
  P(K, 512, 1000, "p_font"), P(K, 480, 1000, "p_crystal", { s: 2 }), P(K, 544, 1000, "p_crystal", { s: 2 });
  K.tag(490, 986, 534, 1000, "rest", { safe: 1 }), K.tag(390, 966, 440, 980, "treasure"), K.tag(560, 986, 640, 1000, "arena");
  shaft(K, 512, 860, 1000, "rope");
