  K.air(140, 900, 800, 960);
  K.water(142, 930, 798, 960);
  for (const [a, b, t] of [[180, 220, 928], [290, 320, 926], [610, 640, 927], [720, 760, 928]]) K.rock(a, t, b, 960);
  K.rock(430, 920, 520, 960);
  K.deep(475, 920);
  P(K, 460, 920, "p_dead"), P(K, 490, 920, "p_moss"), K.tag(440, 906, 510, 920, "rest", { safe: 1 });
  K.tag(180, 912, 330, 928, "arena"), K.tag(610, 912, 760, 928, "arena");
