//   지도 = 칸 1024 × 1056 · 입구 줄 600 · ▲ = 달빛 틈 (x 450) · ▼ = 안개 호수 섬 · 보스 방 = 동쪽 끝 뿔 제단 공동 (x 896~)
//     안개 숲(위 큰 공동): 하얗게 마른 나무가 선 턱 — 턱과 턱을 사슴뿔 모양 뿌리 아치가 잇는다, 안개 웅덩이
//     달빛 틈(▲): 천장 갈라진 틈, 달빛이 내려오는 작은 방
//     사슴 뼈 무덤(아래): 뿔 장식 벽돌 회랑 2층, 막다른 뼈 방(보물)
//     안개 호수(맨 아래): 넓은 물, 가운데 섬 ▼
//     뿔 제단 공동(동쪽 끝): 보스 방 — 둥근 천장 큰 방, 바닥 평평
//   장치: 사다리·덩굴 · 짚라인 · 덩굴 그네 · 무너지는 판 · 금 간 벽 · 회복 샘
