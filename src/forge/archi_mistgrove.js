// ═══ 보스 방: 뿔 제단 공동 (동쪽 끝 128칸) ═══
function arena(K) {
  K.ell(960, 560, 70, 60);
  K.air(900, 520, 1024, EN), K.rock(896, EN, 1024, EN + 24);
  for (const [x, L] of [[920, 20], [950, 30], [980, 24], [1006, 16]]) for (let k = 0; k < L; k++) K.rock(x - Math.max(0, 2 - (k >> 3)), 500 + k, x + Math.max(1, 3 - (k >> 3)), 501 + k);
  P(K, 960, EN, "p_altar"), P(K, 930, EN, "p_bones", { s: 2 }), P(K, 990, EN, "p_skulls");
  K.struct("뿔 제단 공동", "보스", 896, 500, 1024, EN + 8);
}
